"""Generate Telugu audio for lesson content using edge-tts neural voices.

Scans src/lib/content.ts for Telugu strings in LETTERS and WORDS, copies
matching files from the earlier pilot repo when the same text exists there,
generates the rest with edge-tts, and writes src/lib/audioManifest.ts
mapping each Telugu string to its file. Rerun after editing content.

Requires: pip install edge-tts
"""

import asyncio
import hashlib
import re
import shutil
from pathlib import Path

import edge_tts

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "src" / "lib" / "content.ts"
OUT_DIR = ROOT / "public" / "audio"
MANIFEST = ROOT / "src" / "lib" / "audioManifest.ts"

# Earlier pilot repo used only as an asset source: same text means we can
# reuse its generated clip instead of regenerating.
OLD_ROOT = Path(r"D:\githubProjects\DailyTeluguLearning")
OLD_AUDIO = OLD_ROOT / "public" / "audio"
OLD_MANIFEST = OLD_ROOT / "src" / "data" / "audioManifest.ts"

VOICE = "te-IN-ShrutiNeural"
RATE = "-15%"  # slower, clearer for learners

def collect_strings() -> list[str]:
    text = CONTENT.read_text(encoding="utf-8")
    seen: list[str] = []
    for m in re.finditer(r'"([^"]*[\u0C00-\u0C7F][^"]*)"', text):
        s = m.group(1).strip()
        # skip labels/titles; keep strings that are pure Telugu + spaces/punct
        if s and not re.search(r"[A-Za-z()]", s) and s not in seen:
            seen.append(s)
    return seen


def old_manifest() -> dict[str, str]:
    mapping: dict[str, str] = {}
    if not OLD_MANIFEST.exists():
        return mapping
    for m in re.finditer(r"^  '([^']+)': '(/audio/[^']+)'", OLD_MANIFEST.read_text(encoding="utf-8"), re.M):
        mapping[m.group(1).replace("\\'", "'")] = m.group(2)
    return mapping


async def generate(strings: list[str]) -> dict[str, str]:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    old = old_manifest()
    mapping: dict[str, str] = {}
    for i, s in enumerate(strings):
        # Content-addressed name: inserting a string must not shift the
        # filenames of others (a positional index previously made clips
        # play the wrong text after list edits).
        name = f"a{hashlib.sha256(s.encode('utf-8')).hexdigest()[:8]}.mp3"
        dest = OUT_DIR / name
        old_rel = old.get(s)
        if old_rel and (OLD_AUDIO.parent / old_rel.lstrip("/")).exists():
            shutil.copyfile(OLD_AUDIO.parent / old_rel.lstrip("/"), dest)
            print(f"reused {name} from old pilot")
        elif not dest.exists():
            tts = edge_tts.Communicate(s, VOICE, rate=RATE)
            await tts.save(str(dest))
            print(f"generated {name}")
        mapping[s] = f"/audio/{name}"
    return mapping


def write_manifest(mapping: dict[str, str]) -> None:
    lines = [
        "// Generated by scripts/generate_audio.py - do not edit by hand.",
        "// Maps Telugu content strings to generated audio files.",
        "// Voices are computer-generated (Microsoft neural TTS), not human",
        "// recordings; pronunciation still needs native-speaker review.",
        "export const audioFiles: Record<string, string> = {",
    ]
    for telugu, url in mapping.items():
        escaped = telugu.replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"  '{escaped}': '{url}',")
    lines.append("};")
    lines.append("")
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote manifest with {len(mapping)} entries")


async def main() -> None:
    strings = collect_strings()
    print(f"{len(strings)} unique Telugu strings")
    mapping = await generate(strings)
    write_manifest(mapping)


if __name__ == "__main__":
    asyncio.run(main())
